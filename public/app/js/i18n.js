export function detectLang(saved, navLang) {
  if (saved === 'ru' || saved === 'en') return saved;
  return String(navLang || '').toLowerCase().startsWith('ru') ? 'ru' : (navLang ? 'en' : 'ru');
}

export function makeT(lang) {
  const dict = STRINGS[lang] || STRINGS.ru;
  return (key, ...args) => {
    const v = dict[key] ?? STRINGS.ru[key] ?? key;
    return typeof v === 'function' ? v(...args) : v;
  };
}
